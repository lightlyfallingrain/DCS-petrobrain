"""`BL-B111` -- what the pilot hears today vs under the expected-area
look's verdict rules, on the honest harness (`measure_same_group_fold.py`'s
own draws, every draw resampled per trial).

**Stage 0 promotion** (`plans/expected-area-look/plan.md`): this is the
architect's own `plans/expected-area-look/probe_b111.py`, moved here
unchanged (no behaviour change) so it is a tool alongside its siblings
rather than a plan-directory scratch file. Its default mode (no flags) is
still the *modelled* harness described below -- its own output is
`plans/expected-area-look/probe_b111_output.txt`, left as the recorded
architect-time measurement and not regenerated by this move.

The look itself is modelled, not built, in this default mode: it is
"available" whenever A's expected area fits one look (half-width <= 15
deg); terrain, towns and the glass budget are not modelled (flat harness,
one pair). "A observed" = a binocular look at A's true place, attributed
to A by continuity when the gap is inside OBJECT_ID_MEMORY_S, else by
"lies inside A's area" (gate).

**`--production`** (Stage 3c) replaces the model with the real
`ContactStore`/`belief.expected_area` check -- see that mode's own
docstring below for what it drives and what it stubs (the probe answer,
since there is no live DCS Hook in this test environment)."""

from __future__ import annotations

