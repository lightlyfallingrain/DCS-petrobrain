"""Renders `body-layer/config/sequences/triggers.md`, the list of every
effector-sequence trigger a `*.md` sequence file's `run-on-trigger`
header cell may name -- user request, 2026-10-23: *"add a file which
lists (and short description) of the available triggers. It must be
kept up to date as triggers are added (or removed)."*

Triggers are a code enumeration, not a per-aircraft thing (every
aircraft's sequence files draw from the same `EffectorTrigger`), so this
file sits at `config/sequences/` root, one level above the per-aircraft
directories `render_switch_reference.py` writes into.

**Single source of truth**: `belief.effector_sequences.EffectorTrigger`
and `TRIGGER_INFO` (that module's own docstring explains why
`effector_engine.py`'s former second copy of the enum was merged into
this one, 2026-10-23). This tool imports them directly rather than
re-deriving anything -- unlike `generate_defaults.py`, which reads
`tuning.*` declarations via AST specifically to avoid importing modules
that pull in the world-model seam, `effector_sequences.py` and its own
import (`effector_registry.py`) are stdlib-only, so a plain import is
safe here.

Same generator convention as `render_switch_reference.py`/
`generate_defaults.py`: check mode by default, `--write` to regenerate,
a GENERATED header, deterministic output (`EffectorTrigger`'s own
declaration order) so a regeneration diffs cleanly.
`tests/test_render_triggers.py` is this tool's own staleness guard.

Usage (from `body-layer/`):

    python tools/render_triggers.py            # check only, exit 1 if stale
    python tools/render_triggers.py --write    # regenerate config/sequences/triggers.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_BODY_LAYER_ROOT = Path(__file__).resolve().parent.parent
_SRC_DIR = _BODY_LAYER_ROOT / "src"
if str(_SRC_DIR) not in sys.path:
    sys.path.insert(0, str(_SRC_DIR))

from belief.effector_sequences import TRIGGER_INFO, EffectorTrigger

_OUTPUT_PATH = _BODY_LAYER_ROOT / "config" / "sequences" / "triggers.md"

_CARDINALITY_LABEL = {
    "every_time": "every time",
    "once": "once (per mission)",
}


def render_markdown() -> str:
    lines = [
        "# Effector-sequence triggers",
        "",
        "GENERATED by `body-layer/tools/render_triggers.py`. DO NOT HAND-EDIT.",
        (
            "Source: `belief.effector_sequences.EffectorTrigger`/`TRIGGER_INFO` "
            "-- the single place a trigger is declared."
        ),
        "Regenerate with: `python tools/render_triggers.py --write`",
        "",
        "Every trigger a sequence file's `run-on-trigger` header cell may name,",
        "one row per trigger. A trigger fires on the **transition** into the",
        "state it names, never while that state merely holds -- `takeoff` fires",
        "the instant the aircraft leaves the ground, not for every poll it stays",
        "airborne. Sequences for one trigger queue per trigger (firing a",
        "trigger that is already running queues a re-run; it never runs two",
        "copies at once, and never collides with a different trigger's own",
        "queue). A sequence file naming a trigger not listed here is a bad",
        "file -- see `belief.effector_sequences.load_sequences`.",
        "",
        "| Trigger | Fires when | Cardinality |",
        "| --- | --- | --- |",
    ]
    for trigger in EffectorTrigger:
        info = TRIGGER_INFO[trigger]
        lines.append(
            f"| `{trigger.value}` | {info.description} | "
            f"{_CARDINALITY_LABEL[info.cardinality]} |"
        )
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write",
        action="store_true",
        help="write config/sequences/triggers.md; without this, only check staleness",
    )
    args = parser.parse_args()

    rendered = render_markdown()

    if args.write:
        _OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        _OUTPUT_PATH.write_text(rendered, encoding="utf-8")
        print(f"wrote {_OUTPUT_PATH}")
        return 0

    current = _OUTPUT_PATH.read_text(encoding="utf-8") if _OUTPUT_PATH.exists() else ""
    if current != rendered:
        print(
            f"{_OUTPUT_PATH} is stale -- run with --write to regenerate",
            file=sys.stderr,
        )
        return 1
    print(f"{_OUTPUT_PATH} is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
