"""`plans/mock-flight-fixture/plan.md`: a deterministic, fixture-driven
replay of `tests/fixtures/mock_flight_canonical.json` through the real
aircraft-layer HTTP wire shape (`tests/support/mock_aircraft_layer.
MockAircraftLayerServer`), the real body-layer perception/belief pipeline
(`logger._build_sources` + `logger.ConsolePerceptionRunner`), and a real
synthetic world-model store (`tests/support/mock_world_model`), asserting
the whole chain reaches a known `belief.contacts.ContactStore` end state.

This is the one test in this suite that exercises the full chain a single
source-plus-`ContactStore` fixture test (`test_emission_pipeline.py`) or a
pure-belief fixture test (`test_contacts.py`) structurally cannot: two real
sources sharing one poll's HTTP round trip, a real (if flat/synthetic)
terrain LOS gate instead of a monkeypatched `visibility.
line_of_sight_clear`, and -- in the second test below -- the real
`--console` threading model (`logger._run_console_poll_loop` on a
background thread, `belief.console.Console` dispatch on the foreground
thread), catching the class of cross-thread `sqlite3.ProgrammingError` bug
`test_logger.py`'s own Stage 6/BL-5 regression tests were written for, but
now against two sources and many consecutive polls instead of one.

**Only a wiring proof, not a terrain-accuracy claim** -- see
`tests/support/mock_world_model.py`'s own docstring: the synthetic store's
flat, low elevation grid makes every line-of-sight check in this fixture
clear by construction. Real-terrain LOS correctness is the World Model
Builder's own control-point tests' job.

**Fixture intent** (`tests/fixtures/mock_flight_canonical.json`, 20 poll
frames, generated by converting known DCS x/z positions through the real
world-model `coordinates.dcs_to_wgs84` -- no monkeypatched coordinate
transform, per the plan's decision to exercise real geometry end to end):

- Ownship flies a straight track due north (heading 0 deg true) from DCS
  `(x=0, z=0)` to `(x=1140, z=0)`, climbing/descending never -- constant
  700 m MSL, t_sim advancing 5 s/poll.
- **`object_id=101`, `"Ural-375"` (DCS reporting name `"Ural truck"`),
  stationary at `(x=1400, z=0, alt=500)`, dead ahead the whole flight.**
  This is the plan's "continuously visible and stationary" object (the
  duplicate-contact regression shape). The Hybrid channel detects it every
  poll from frame 0 (`petrovich_indication.fields.middle_list_text ==
  "Ural truck"` in every frame, always in range/forward hemisphere),
  founding a `TYPE`-level `"Ural truck"` contact immediately; the naked-eye
  channel also tracks it every poll, starting at `medres` tier (class-level
  `"OP_TRUCK"`, range ~1414 m) and crossing the `hires` threshold (1200 m)
  at frame 4. **Running the harness once (not guessed) showed this does
  not produce a mid-flight `CONTACT_CLASSIFICATION_CHANGED` event**: Hybrid's
  frame-0 percept already establishes the contact at `TYPE` level, and
  `belief.classification.fold_classification`'s "lower level holds" rule
  (a same- or coarser-level claim never downgrades an already-established
  finer one) means every later naked-eye `CLASS`-level percept -- both
  before and after its own `medres`->`hires` crossing -- folds in without
  changing the contact's held classification at all. This is real, correct
  behavior worth documenting rather than the reclassification-event scenario
  originally sketched for this object: it demonstrates the classification
  lattice's monotonicity *and* cross-channel correlation onto one contact
  (never two) at the same time, which is exactly what a duplicate-contact
  regression test needs.
- **`object_id=102`, `"Infantry AK"` (reporting name `"Soldier AK"`),
  stationary at `(x=1800, z=0, alt=500)`.** The plan's "appears mid-flight"
  object: present in `world_objects` ground truth from frame 0 (DCS ground
  truth is never gated), but outside the naked-eye visibility gate's range
  threshold (~1674 m) until frame 3, when the shrinking ownship-to-object
  range first clears it -- `lowres` tier initially, refining to `medres` by
  frame 16 as range keeps shrinking. Never referenced by
  `petrovich_indication` text, so it is naked-eye-only, unlike object 101 --
  this is what keeps the fixture's Hybrid-channel behavior simple to reason
  about (exactly one classification text, `"Ural truck"`, ever appears on
  that channel).

Exact per-frame range/tier numbers were computed by a throwaway script
against the real formulas in `perception.visibility`/`perception.geometry`
before authoring the fixture (not guessed) -- see
`plans/mock-flight-fixture/implementation.md` for that derivation. The
`ContactStore` end-state assertions below were derived by actually running
this harness once and inspecting its output (per the plan's explicit
instruction not to guess-then-backfill), then sanity-checked against the
intent above.
"""

from __future__ import annotations

import io
import json
import sys
